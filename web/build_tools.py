"""Generate browser-safe cores from the original demos and copy static assets."""
import ast
import json
import shutil
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / 'web/dist'


def browser_core(source, filename, omit, excluded_imports):
    tree = ast.parse(source.read_text(encoding='utf-8-sig'))
    nodes = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name in omit:
            continue
        if isinstance(node, ast.If):
            continue
        if isinstance(node, ast.Import):
            aliases = [a for a in node.names if a.name not in excluded_imports]
            if not aliases:
                continue
            node.names = aliases
        if isinstance(node, ast.ImportFrom) and node.module in excluded_imports:
            continue
        nodes.append(node)
    code = '# Generated by web/build_tools.py from the original demo.\n' + ast.unparse(ast.Module(body=nodes, type_ignores=[])) + '\n'
    (DIST / 'python' / filename).write_text(code, encoding='utf-8')


def build():
    browser_core(ROOT / '1_請求書読み取り/extract_invoices.py', 'invoice_core.py',
                 {'text_lines_from_pdf', 'deskew', 'ocr_lines', 'read_pdf', 'process', 'main'},
                 {'pymupdf', 'PIL', 'numpy', 'pytesseract'})
    browser_core(ROOT / '2_焼肉店営業リスト/yakiniku_leads.py', 'leads_core.py',
                 {'PlacesClient', 'MockPlacesClient', 'search_area', 'enrich_with_details', 'run', 'parse_args'},
                 {'requests'})
    data_dir = DIST / 'data'
    samples = data_dir / 'invoices'
    samples.mkdir(parents=True, exist_ok=True)
    for path in sorted((ROOT / '1_請求書読み取り/samples').glob('*.pdf')):
        shutil.copyfile(path, samples / path.name)
    mock_dir = ROOT / '2_焼肉店営業リスト/mock'
    index = json.loads((mock_dir / 'index.json').read_text(encoding='utf-8'))
    places = []
    for query, filename in index['queries'].items():
        while filename:
            response = json.loads((mock_dir / filename).read_text(encoding='utf-8'))
            for place in response.get('places', []):
                place['_query'] = query
                places.append(place)
            filename = index['pages'].get(response.get('nextPageToken'))
    (data_dir / 'leads.json').write_text(json.dumps({'places': places}, ensure_ascii=False, indent=2), encoding='utf-8')
    vendor = DIST / 'vendor'
    pdf = vendor / 'pdfjs'
    pdf.mkdir(parents=True, exist_ok=True)
    for filename in ['pdf.mjs', 'pdf.worker.mjs']:
        shutil.copyfile(ROOT / 'web/node_modules/pdfjs-dist/build' / filename, pdf / filename)
    for directory in ['cmaps', 'standard_fonts', 'wasm']:
        shutil.copytree(ROOT / 'web/node_modules/pdfjs-dist' / directory, pdf / directory, dirs_exist_ok=True)
    shutil.copyfile(ROOT / 'web/node_modules/pdfjs-dist/LICENSE', pdf / 'LICENSE')
    tess = vendor / 'tesseract'
    tess.mkdir(exist_ok=True)
    for filename in ['tesseract.min.js', 'worker.min.js']:
        shutil.copyfile(ROOT / 'web/node_modules/tesseract.js/dist' / filename, tess / filename)
    shutil.copyfile(ROOT / 'web/node_modules/tesseract.js/LICENSE.md', tess / 'LICENSE.md')
    for filename in ['tesseract.min.js.LICENSE.txt', 'worker.min.js.LICENSE.txt']:
        shutil.copyfile(ROOT / 'web/node_modules/tesseract.js/dist' / filename, tess / filename)
    core = vendor / 'tesseract-core'
    core.mkdir(exist_ok=True)
    for path in (ROOT / 'web/node_modules/tesseract.js-core').glob('tesseract-core*'):
        if 'lstm' in path.name and path.name.endswith(('.js', '.wasm')):
            shutil.copyfile(path, core / path.name)
    shutil.copyfile(ROOT / 'web/node_modules/tesseract.js-core/LICENSE', core / 'LICENSE')
    language_dir = vendor / 'tessdata-best'
    language_dir.mkdir(exist_ok=True)
    for language in ['jpn']:
        target = language_dir / f'{language}.traineddata.gz'
        if not target.exists():
            urllib.request.urlretrieve(f'https://cdn.jsdelivr.net/npm/@tesseract.js-data/{language}@1.0.0/4.0.0/{language}.traineddata.gz', target)
    shutil.copyfile(ROOT / 'web/node_modules/tesseract.js/LICENSE.md', language_dir / 'LICENSE.md')
    print(f'Built browser tools: {len(places)} mock places, {len(list(samples.glob("*.pdf")))} sample invoices')


if __name__ == '__main__':
    build()
